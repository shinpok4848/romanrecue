import { getStructureProfile } from './structureProfiles.js';

export const DEFAULT_EXCLUDE = [
  'vocal fry',
  'scratchy voice',
  'robotic',
  'autotune',
  'volume pumping',
  'muddy mix',
  'off-beat',
  'boring intro',
  'digital clipping',
  'harsh sibilance',
  'phase cancellation',
  'over-compression',
];

function preset({ vocalOptions, ...data }) {
  const structureProfile = getStructureProfile(data.structureId);
  return {
    ...data,
    vocalOptions: vocalOptions.map((option) => ({ ...option })),
    // Kept for v1 callers and external consumers.
    vocalCharacterizations: vocalOptions.map((option) => option.phrase),
    vocalGender: vocalOptions[0]?.gender || 'Female',
    lyricStructure: [...structureProfile.sections],
  };
}

