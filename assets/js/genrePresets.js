export const PRESET_BY_ID = Object.fromEntries(ALL_PRESETS.map((item) => [item.id, item]));

export function getPool(mood) {
  return mood === 'energetic' ? ENERGETIC : EMOTIONAL;
}

export function getPresetById(id) {
  return PRESET_BY_ID[id] || null;
}
